class TestVisibilityFlips:
    def test_internal_to_public_and_back_changes_customer_rls(self, kb_documents):
        http = kb_admin_http()
        _use_role(_ADMIN_ROLE)

        document_id = _doc_id(_INTERNAL_DOC_KEY)

        def customer_sees_document() -> bool:
            rows = _rls_select_rows(
                user_id=_CUSTOMER_ROLE,
                sql="SELECT id::text FROM public.documents WHERE id = %s",
                params=(document_id,),
            )
            return bool(rows)

        assert not customer_sees_document()

        response = http.patch(
            f"{VISIBILITY_PATH_PREFIX}{document_id}",
            json={"visibility": "public"},
        )
        assert response.status_code == status.HTTP_200_OK
        assert response.json()["visibility"] == "public"

        try:
            assert customer_sees_document(), (
                "public flip did not take effect for customer RLS"
            )

            # Flip back to internal; the grant must be withdrawn
            # immediately (read-time policy evaluation).
            response = http.patch(
                f"{VISIBILITY_PATH_PREFIX}{document_id}",
                json={"visibility": "internal"},
            )
            assert response.status_code == status.HTTP_200_OK
            assert response.json()["visibility"] == "internal"

            assert not customer_sees_document(), (
                "internal flip did not withdraw customer access"
            )
        finally:
            # The module fixture deletes the row at teardown; restore
            # the internal default in case the flip-back failed mid-test.
            row = _fetch_document_row(document_id)
            if row is not None and row["visibility"] != "internal":
                _use_role(_ADMIN_ROLE)
                http.patch(
                    f"{VISIBILITY_PATH_PREFIX}{document_id}",
                    json={"visibility": "internal"},
                )

    def test_visibility_error_is_sanitized(self, kb_documents):
        _use_role(_ADMIN_ROLE)
        http = kb_admin_http()

        response = http.patch(
            f"{VISIBILITY_PATH_PREFIX}{_doc_id(_INTERNAL_DOC_KEY)}",
            json={"visibility": "top_secret_v2"},
        )
        assert response.status_code == status.HTTP_422_UNPROCESSABLE_ENTITY
        assert "storage" not in response.json()
        assert "uploads/" not in str(response.json())


