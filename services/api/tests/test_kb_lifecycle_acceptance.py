        _use_role(_ADMIN_ROLE)
        http = kb_admin_http()

        caplog.set_level(logging.DEBUG)

        document_id = None
        try:
            response = http.post(
                UPLOAD_PATH,
                files={"file": ("Internal Operations Handbook.pdf",
                                INTERNAL_OPERATIONS_HANDBOOK_PDF_BYTES,
                                "application/pdf")},
                data={"visibility": "internal"},
            )
            document_id = response.json().get("id")

            storage_path = (
                _fetch_document_row(document_id)["storage_path"]
                if document_id
                else None
            )
            chunk_contents = (
                [chunk["content"] for chunk in _fetch_chunks(document_id)]
                if document_id
                else []
            )
            embedding_texts = (
                _fetch_embedding_texts(document_id) if document_id else []
            )

            captured = "\n".join(
                str(record.getMessage())
                for record in caplog.records
                # The app's own logging contract is what this test
                # verifies; third-party SDK debug output (which logs
                # HTTP URLs) is out of scope for this assertion.
                if record.name.startswith("app")
            )

            if storage_path:
                assert storage_path not in captured
            assert "uploads/" not in captured
            for marker in KNOWLEDGE_BASE_ACCEPTANCE_MARKERS:
                assert marker not in captured
            for content in chunk_contents:
                assert content not in captured
            for vector_text in embedding_texts:
                # A pgvector vector renders as "[0.0123,-0.98,...]" —
                # the leading segment is a strong identifying prefix.
                assert vector_text[:24] not in captured
        finally:
            if document_id:
                _use_role(_ADMIN_ROLE)
                _cleanup_documents({document_id: {}})


