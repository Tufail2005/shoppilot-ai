"""Phase 5.10 end-to-end knowledge-base acceptance run.

Roadmap requirement for this phase:

    phase 5.10 — Test with 2 PDFs: one public (return policy),
    one internal (ops handbook)

This module validates the complete document lifecycle against the REAL
local Supabase services with the REAL Gemini embedding provider:

- the upload runs through the real POST /admin/documents endpoint,
- Storage behavior runs against the real local Storage service (the
  dependency override supplies the real Storage facade instead of a
  fake: prior phases proved that fakes and the real service can
  disagree),
- the database is the real local PostgreSQL with the real RLS
  policies, verified by switching to the real ``authenticated`` role
  with simulated JWT claims (the technique established in Phase 3.10
  and reused in the Phase 5.9 visibility tests; the application's own
  service-role pool deliberately bypasses RLS and therefore cannot be
  used for these checks),
- embeddings are generated by the real Gemini embedding API.

Opt-in and prerequisites (this module always runs with the real
provider; there is deliberately no fake fallback here, because the
Phase 5.6-5.9 suites already validate orchestration with fakes):

- local Supabase stack running (``supabase start``): the module skips
  cleanly when the Storage service is unreachable, and
  ``tests/conftest.py`` already gates the database;
- ``GEMINI_API_KEY`` configured in ``services/api/.env``: without it
  the whole module skips — the live run stays pending, never faked;
  a configured-but-failing key or API is NOT skipped: the upload then
  records a ``failed`` document whose ``failure_stage`` makes the
  live blocker explicit in the failing assertion.

Hygiene:

- both sample PDFs are generated in memory (tests/kb_acceptance_pdfs)
  and never written to disk;
- fixture cleanup runs even when intermediate assertions fail: it
  deletes only the documents created by this module (pinned to the
  exact UUIDs returned by the upload responses) via the real admin
  deletion endpoint, with a direct-database fallback, and then
  verifies zero residue (rows, cascaded chunks, Storage objects);
- pre-existing documents and Storage objects are never touched;
- no document content, embedding value, or storage path is ever
  printed through the logging in this module;
- the module teardown clears every dependency override it installed,
  so later test modules never observe a leftover override.
"""

