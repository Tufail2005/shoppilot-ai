def _fetch_document_row(document_id: str) -> dict | None:
    with _connect() as connection, connection.cursor() as cursor:
        cursor.execute(
            """
            SELECT id::text, title, status, visibility, version,
                   failure_stage, failure_message, storage_path
            FROM public.documents
            WHERE id = %s
            """,
            (document_id,),
        )
        row = cursor.fetchone()
        if row is None:
            return None
        return {
            "id": row[0],
            "title": row[1],
            "status": row[2],
            "visibility": row[3],
            "version": row[4],
            "failure_stage": row[5],
            "failure_message": row[6],
            "storage_path": row[7],
        }


def _fetch_chunks(document_id: str) -> list[dict]:
    with _connect() as connection, connection.cursor() as cursor:
        cursor.execute(
            """
            SELECT chunk_index, content,
                   embedding IS NOT NULL, vector_dims(embedding)
            FROM public.document_chunks
            WHERE document_id = %s
            ORDER BY chunk_index
            """,
            (document_id,),
        )
        return [
            {
                "chunk_index": row[0],
                "content": row[1],
                "has_embedding": row[2],
                "dimensions": row[3],
            }
            for row in cursor.fetchall()
        ]


def _fetch_embedding_texts(document_id: str) -> list[str]:
    with _connect() as connection, connection.cursor() as cursor:
        cursor.execute(
            """
            SELECT embedding::text
            FROM public.document_chunks
            WHERE document_id = %s
            ORDER BY chunk_index
            """,
            (document_id,),
        )
        return [row[0] for row in cursor.fetchall()]


def _db_delete_document_row(document_id: str) -> None:
    with _connect() as connection, connection.cursor() as cursor:
        cursor.execute(
            "DELETE FROM public.documents WHERE id = %s",
            (document_id,),
        )


def _storage_object_exists(storage_path: str) -> bool:
    """True when the object can be downloaded from the real bucket."""

    try:
        _real_storage_facade().from_(DOCUMENTS_BUCKET).download(storage_path)
    except Exception:
        return False
    return True


def _rls_select_rows(*, user_id: str, sql: str, params: tuple) -> list[tuple]:
    """Run a SELECT through the real RLS machinery as one seeded user."""

    with _connect() as connection, connection.cursor() as cursor:
        cursor.execute("set local role authenticated")
        cursor.execute(
            "select set_config('request.jwt.claims', %s, true)",
            (json.dumps({"sub": user_id, "role": "authenticated"}),),
        )
        cursor.execute(sql, params)
        return cursor.fetchall()


