@pytest.fixture(scope="module")
def kb_documents(live_gemini):
    """Upload both sample PDFs through the real endpoint; clean up after.

    Requires the real Storage override (installed by the autouse
    module fixture) and leaves the REAL ``get_embedding_provider``
    dependency un-overridden so the real Gemini API is exercised.

    Cleanup runs even when an upload assertion fails.  Only the exact
    document ids created here are touched.  The residue check is
    performed for every id, so teardown reports leftovers loudly.
    """

    uploads: dict[str, dict] = {}  # document_id -> upload response body

    def _upload(who, filename, visibility, pdf_bytes):
        response = who.post(
            UPLOAD_PATH,
            files={"file": (filename, pdf_bytes, "application/pdf")},
            data={"visibility": visibility},
        )
        body = response.json()

        assert response.status_code == status.HTTP_201_CREATED, (
            f"Upload of {filename!r} did not return 201: "
            f"{response.status_code} {body}"
        )

        # A real-Gemini failure lands here: the document is created but
        # `failed`, and failure_stage identifies the live blocker
        # (e.g. embedding_generation).
        assert body["status"] == "ready", (
            "Live ingestion reported failure. failure_stage="
            f"{body.get('failure_stage')!r}; "
            f"failure_message={body.get('failure_message')!r}. "
            "If failure_stage is 'embedding_generation', the live Gemini "
            "embedding acceptance is blocked."
        )

        document_id = body["id"]
        uploads[document_id] = body

        row = _fetch_document_row(document_id)
        assert row is not None, "uploaded document row missing"
        _storage_paths[document_id] = row["storage_path"]

        return body

    try:
        _use_role(_ADMIN_ROLE)
        _documents[_PUBLIC_DOC_KEY] = _upload(
            kb_admin_http(),
            PUBLIC_RETURN_POLICY_FILENAME,
            "public",
            PUBLIC_RETURN_POLICY_PDF_BYTES,
        )

        _use_role(_AGENT_ROLE)
        _documents[_INTERNAL_DOC_KEY] = _upload(
            kb_admin_http(),
            INTERNAL_OPERATIONS_HANDBOOK_FILENAME,
            "internal",
            INTERNAL_OPERATIONS_HANDBOOK_PDF_BYTES,
        )

        yield _documents
    finally:
        _use_role(_ADMIN_ROLE)
        try:
            _cleanup_documents(uploads)
        finally:
            # Never leave a login override installed for later tests.
            app.dependency_overrides.pop(get_current_user, None)


def kb_admin_http():
    """The session-scoped TestClient.

    Roles are selected explicitly per request-batch through
    ``_use_role`` (the single ``get_current_user`` override slot makes
    concurrent role fixtures impossible).
    """

    return _session_client[0]


_session_client: list = []


def _cleanup_documents(uploads):
    """Delete only this run's documents; then verify zero residue.

    Two layers, so cleanup still runs when one layer fails:
    1. the real admin deletion endpoint (204, or 404 once already gone),
    2. a direct Storage remove + database DELETE fallback for an id
       whose endpoint deletion did not succeed.

    The residue assertions raise, so pytest reports any leftover as a
    teardown error — a failed validation is never misreported as clean.
    """

    http = kb_admin_http()

    for document_id in uploads:
        row = None
        try:
            row = _fetch_document_row(document_id)
        except Exception:
            row = None

        endpoint_ok = False
        try:
            response = http.delete(f"{VISIBILITY_PATH_PREFIX}{document_id}")
            endpoint_ok = response.status_code in (
                status.HTTP_204_NO_CONTENT,
                status.HTTP_404_NOT_FOUND,
            )
            if not endpoint_ok:
                print(
                    "Endpoint cleanup returned "
                    f"{response.status_code} for {document_id}"
                )
        except Exception as exc:
            print(
                "Endpoint cleanup raised for "
                f"{document_id}: {type(exc).__name__}"
            )

        if not endpoint_ok:
            # Fallback: remove the Storage object (the path is known
            # from the fallback row or the post-upload capture), then
            # the row; chunks cascade with the row.
            storage_path = (row or {}).get("storage_path") or _storage_paths.get(
                document_id
            )
            if storage_path:
                try:
                    _real_storage_facade().from_(DOCUMENTS_BUCKET).remove(
                        [storage_path]
                    )
                except Exception as exc:
                    print(
                        "Fallback Storage removal failed for "
                        f"{document_id}: {type(exc).__name__}"
                    )
            try:
                _db_delete_document_row(document_id)
            except Exception as exc:
                print(
                    "Fallback DB deletion failed for "
                    f"{document_id}: {type(exc).__name__}"
                )

        # Residue check, independent of which layer succeeded.
        residual_row = _fetch_document_row(document_id)
        path = (residual_row or {}).get("storage_path") or _storage_paths.get(
            document_id
        )

        if residual_row is not None:
            # The row should already be gone; force a loud failure on
            # residue after removing the leftover directly.
            _db_delete_document_row(document_id)
            residual_row = _fetch_document_row(document_id)

        assert residual_row is None, (
            f"Acceptance residue: document row {document_id} survived cleanup"
        )
        assert _fetch_chunks(document_id) == [], (
            f"Acceptance residue: chunks of {document_id} survived cleanup"
        )
        if path is not None:
            assert not _storage_object_exists(path), (
                f"Acceptance residue: Storage object of {document_id} "
                "survived cleanup"
            )


