class TestRlsAuthorization:
    def test_customer_sees_public_document_and_its_chunks(self):
        document_id = _doc_id(_PUBLIC_DOC_KEY)

        rows = _rls_select_rows(
            user_id=_CUSTOMER_ROLE,
            sql=(
                "SELECT id::text, visibility, status FROM public.documents "
                "WHERE id = %s"
            ),
            params=(document_id,),
        )
        assert len(rows) == 1
        assert rows[0][1] == "public"
        assert rows[0][2] == "ready"

        expected_chunks = len(_fetch_chunks(document_id))
        chunk_rows = _rls_select_rows(
            user_id=_CUSTOMER_ROLE,
            sql=(
                "SELECT count(*) FROM public.document_chunks "
                "WHERE document_id = %s"
            ),
            params=(document_id,),
        )
        assert chunk_rows[0][0] == expected_chunks > 0

    def test_customer_cannot_see_internal_document_or_chunks(self):
        document_id = _doc_id(_INTERNAL_DOC_KEY)

        rows = _rls_select_rows(
            user_id=_CUSTOMER_ROLE,
            sql="SELECT id::text FROM public.documents WHERE id = %s",
            params=(document_id,),
        )
        assert rows == [], "customer saw an internal document"

        chunk_rows = _rls_select_rows(
            user_id=_CUSTOMER_ROLE,
            sql=(
                "SELECT count(*) FROM public.document_chunks "
                "WHERE document_id = %s"
            ),
            params=(document_id,),
        )
        assert chunk_rows[0][0] == 0, "customer saw chunks of an internal document"

    def test_employee_can_access_internal_document_and_chunks(self):
        document_id = _doc_id(_INTERNAL_DOC_KEY)
        expected_chunks = len(_fetch_chunks(document_id))

        for user_id in (_AGENT_ROLE, _ADMIN_ROLE):
            rows = _rls_select_rows(
                user_id=user_id,
                sql=(
                    "SELECT id::text, visibility FROM public.documents "
                    "WHERE id = %s"
                ),
                params=(document_id,),
            )
            assert len(rows) == 1, f"user {user_id} cannot see internal doc"
            assert rows[0][1] == "internal"

            chunk_rows = _rls_select_rows(
                user_id=user_id,
                sql=(
                    "SELECT count(*) FROM public.document_chunks "
                    "WHERE document_id = %s"
                ),
                params=(document_id,),
            )
            assert chunk_rows[0][0] == expected_chunks, (
                f"user {user_id} cannot see internal chunks"
            )

    def test_anon_role_is_denied_document_access(self):
        # The documents/SELECT policy applies only to the
        # authenticated role. With RLS enabled and no anon policy, the
        # real behavior for anon is an EMPTY result (RLS denial), not a
        # privilege error — the local CLI auto-grants SELECT to anon,
        # matching the cloud default (see supabase/config.toml),
        # while the repo's own migrations grant SELECT only to
        # authenticated.
        for sql in (
            "SELECT id::text FROM public.documents WHERE id = ANY(%s::uuid[])",
            "SELECT id::text FROM public.document_chunks "
            "WHERE document_id = ANY(%s::uuid[])",
        ):
            with _connect() as connection, connection.cursor() as cursor:
                cursor.execute("set local role anon")
                cursor.execute(
                    sql,
                    ([
                        _doc_id(_PUBLIC_DOC_KEY),
                        _doc_id(_INTERNAL_DOC_KEY),
                    ],),
                )
                assert cursor.fetchall() == [], (
                    "anon role unexpectedly retrieved document data through RLS"
                )


