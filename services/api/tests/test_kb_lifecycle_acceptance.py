        assert all(chunk["has_embedding"] for chunk in chunks)
        assert all(chunk["dimensions"] == 768 for chunk in chunks)

        joined_content = " ".join(chunk["content"] for chunk in chunks)
        assert KNOWLEDGE_BASE_ACCEPTANCE_MARKERS[0] in joined_content


