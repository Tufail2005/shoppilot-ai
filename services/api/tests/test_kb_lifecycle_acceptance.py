def _connect() -> psycopg.Connection:
    return psycopg.Connection.connect(_LOCAL_DATABASE_URL, connect_timeout=5)


def _real_storage_facade():
    """The real local Storage facade, or pytest.skip when unreachable."""

    facade = create_client(LOCAL_SUPABASE_URL, _LOCAL_SERVICE_ROLE_KEY).storage

    try:
        # Cheap reachability probe against the real Storage service.
        facade.from_(DOCUMENTS_BUCKET).list("probe/_phase_5_10")
    except Exception as exc:
        pytest.skip(
            "Phase 5.10 acceptance requires the local Supabase Storage "
            f"service (start it with `supabase start`): {type(exc).__name__}"
        )
        raise  # unreachable; makes control flow explicit for linters

    return facade


