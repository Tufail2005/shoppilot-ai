class TestRealEmbeddings:
    def test_vectors_are_distinct_per_chunk_and_nonzero(self, kb_documents):
        for key in (_PUBLIC_DOC_KEY, _INTERNAL_DOC_KEY):
            document_id = _doc_id(key)
            texts = _fetch_embedding_texts(document_id)
            expected_count = len(_fetch_chunks(document_id))

            assert len(texts) == expected_count
            # Real Gemini vectors differ per chunk; one aggregated
            # embedding for the whole document would collapse here.
            assert len(set(texts)) == expected_count, (
                f"{key}: embeddings are not per-chunk distinct"
            )

            # No vector collapsed to an all-zero placeholder.
            for text in texts:
                leading_values = [
                    float(value) for value in text.strip("[]").split(",")[:16]
                ]
                assert any(value != 0.0 for value in leading_values), (
                    f"{key}: an embedding looks degenerate (all zeros)"
                )


