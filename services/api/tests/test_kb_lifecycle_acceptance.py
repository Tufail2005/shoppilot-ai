# Module-level cache of the two documents created by this run.
# Populated by the upload fixture BEFORE any test runs; read directly by
# the RLS helpers (plain functions cannot request pytest fixtures).
_documents: dict[str, dict] = {}
# document id -> storage_path, captured from the row right after upload
# (the API responses deliberately never carry the path).
_storage_paths: dict[str, str] = {}


def _doc(key: str) -> dict:
    return _documents[key]


def _doc_id(key: str) -> str:
    return _documents[key]["id"]


def _use_role(user_id: str) -> None:
    """Authenticate the app as one seeded user for the next requests.

    Explicit per-call instead of a module-scoped fixture: the
    dependency-overrides dictionary has a single ``get_current_user``
    entry, so module-scoped role fixtures would clobber each other.
    The module autouse teardown clears everything afterwards.
    """
    app.dependency_overrides[get_current_user] = _override_get_current_user(
        user_id
    )


